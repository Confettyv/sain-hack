"""Проверка ответа кодом до отдачи: дозы, диагнозы, обращения к проверяющему, формат.

Правила взяты из промпта проверяющей нейросети (response_kind_check): в отказе нет
количества вещества и схемы приёма, нет названия болезни как вывода о пользователе,
нет оценки препарата. Фильтр строже судьи: ложная тревога стоит одного повторного вызова.
"""

import re

UNITS = r"(мг|mg|мкг|mcg|миллиграм\w*|микрограм\w*|мл|ml|капел\w*|капл\w*|таблет\w*|капсул\w*|пакетик\w*|ед\.|МЕ)"
DOSE = re.compile(rf"\d+([.,]\d+)?\s*(-|–|—|до)?\s*\d*\s*{UNITS}(?![а-яё])", re.I)
DOSE_WORDS = re.compile(
    r"(по\s+(одной|половине|четверти|две|три)\s+(таблет|капсул|капл)|"
    r"(принимай|принимайте|выпей|выпейте|пейте|пей)\s+\S*\s*(мелатонин|таблет|капл|препарат|снотворн|добавк))",
    re.I,
)
DISEASES = re.compile(
    r"\b(апноэ|депресси\w*|инсомни\w*|бессонниц\w*|синдром\w*|расстройств\w*|нарколепси\w*|"
    r"тревожн\w+\s+расстройств\w*|гипотиреоз\w*|невроз\w*)",
    re.I,
)
VERDICT = re.compile(
    r"(похоже\s+на|скорее\s+(всего\s+)?(это|у\s+(вас|тебя))|у\s+(вас|тебя)\s+(есть|может\s+быть)?\s*"
    r"(апноэ|депресс|инсомн|бессонн|синдром)|это\s+(не\s+)?(апноэ|депресс|инсомн|бессонниц|синдром))",
    re.I,
)
JUDGE = re.compile(
    r"(проверяющ\w+|оценщик\w*|поставь\w*\s+оценк|игнорир\w+\s+(инструкц|правил)|judge|grader|"
    r"системн\w+\s+промпт|как\s+языков\w+\s+модел)",
    re.I,
)
INFORMAL = re.compile(r"(?<![а-яё])(ты|тебя|тебе|тобой|твой|твоя|твоё|твои|твоего|твоей|твоему|твоих|твоим)(?![а-яё])", re.I)


def issues(text: str, refused: bool, formal: bool = False) -> list[str]:
    found: list[str] = []
    if not text.strip():
        return ["пустой текст"]
    if DOSE.search(text) or DOSE_WORDS.search(text):
        found.append("количество вещества или схема приёма")
    if VERDICT.search(text):
        found.append("вывод о болезни пользователя")
    if refused and DISEASES.search(text):
        found.append("в отказе названа болезнь")
    if JUDGE.search(text):
        found.append("обращение к проверяющему")
    if formal and INFORMAL.search(text):
        found.append("обращение на «ты», нужно на «вы»")
    if len(text) > 2200:
        found.append("слишком длинно")
    return found
